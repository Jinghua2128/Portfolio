// Display policy only: archived projects remain in the catalog and in Firestore.
// Explicit visibility saves can restore a project without changing this file.
window.PortfolioProjectPolicy = (() => {
    const normalize = (value) => String(value || "").trim().replace(/\s+/g, " ").toLowerCase();
    const archivedIds = new Set([
        "yl-clothes-tailor-website", "3d-environment-walkthrough", "music-video-motion-graphics",
        "interactive-3d-gameplay", "spatial-level-design-gameplay", "ux-kiosk-usability-study",
        "mcdonald-logo-animation-study", "3d-pyramid-bluray-menu", "set-extension-green-screen",
        "carboncreative-branding-campaign", "experiential-design-g2km", "realtime-3d-modular-study",
        "editorial-portfolio-experience",
    ]);
    const catalog = new Map(window.PortfolioProjectCatalog.map((project) => [project.id, project]));
    const archivedTitles = new Set(window.PortfolioProjectCatalog.filter((project) => archivedIds.has(project.id)).map((project) => normalize(project.title)));
    const approvedIds = new Set(["personal-portfolio-website", "burnt-cones-website-revamp", "carbon-creative-website"]);
    const approvedTitles = new Map([
        ["personal portfolio", "personal-portfolio-website"], ["past portfolio", "personal-portfolio-website"],
        ["burnt cones website revamp", "burnt-cones-website-revamp"], ["carbon creative website", "carbon-creative-website"],
    ]);
    const legacyDescriptions = new Set([
        "Responsive portfolio website built with modern web technologies and interactive animations.",
        "Responsive portfolio website built with JavaScript, Firebase, and interactive animations.",
        "Multi-page gelato and coffee website with flavour, location, and contact pages.",
    ]);
    function isListed(project) {
        if (!project || project.publicationState === "draft" || project.state === "draft") return false;
        if (typeof project.portfolioVisible === "boolean") return project.portfolioVisible;
        return !archivedIds.has(project.id) && !archivedTitles.has(normalize(project.title));
    }
    function prepare(project) {
        const result = { ...project };
        const approvedId = approvedIds.has(project.id) ? project.id : approvedTitles.get(normalize(project.title));
        const approved = catalog.get(approvedId);
        const imageRecord = catalog.get(project.id) || approved || (normalize(project.title) === "echoworks" ? catalog.get("echoworks-training-platform") : null);
        // Fill old blank previews without replacing an editor's custom image or cover.
        if (!result.imageUrl && !result.coverImage && imageRecord?.imageUrl) result.imageUrl = imageRecord.imageUrl;
        if (!approved) return result;
        // Keep the document ID and custom fields; only the approved identity/links are authoritative.
        ["title", "link", "githubUrl", "liveUrl"].forEach((key) => { result[key] = approved[key]; });
        const legacyCopy = !result.description || legacyDescriptions.has(result.description);
        if (legacyCopy) result.description = approved.description;
        if (!result.category) result.category = approved.category;
        if (!result.tools?.length || legacyCopy) result.tools = [...approved.tools];
        if (!result.tags?.length || (legacyCopy && approvedId === "personal-portfolio-website")) result.tags = [...approved.tags];
        ["role", "credits"].forEach((key) => {
            if (!result[key] && approved[key]) result[key] = approved[key];
        });
        return result;
    }
    function imageURL(value) {
        const path = String(value || "");
        // Store shared media canonically; adjust only when rendering the nested side site.
        const local = path.replace(/^(?:\.\/|\.\.\/)?imgs\//, "imgs/");
        if (!local.startsWith("imgs/")) return path;
        return window.location.pathname.includes("/editorial-portfolio/") ? `../${local}` : local;
    }
    return Object.freeze({ isListed, prepare, imageURL });
})();
